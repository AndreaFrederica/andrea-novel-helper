// Hybrid script sample: both run() and activate().
// Expected type in UI: 混合脚本, tags include Typst 渲染器

export async function activate(ctx) {
  ctx.renderers.registerTypst(
    {
      id: 'sample.minimal.typst',
      label: 'Sample Minimal Typst Renderer',
      description: 'Return a tiny Typst document from render context',
    },
    async (input) => {
      const title = input?.renderContext?.project?.name || 'Untitled';
      const now = new Date().toISOString();
      return {
        typContent: `= ${title}\n\nGenerated by sample.minimal.typst\n\n- Time: ${now}\n`,
      };
    }
  );
}

export async function run(ctx) {
  const msg = {
    ok: true,
    script: '04-hybrid-typst-renderer',
    note: 'This script is both runnable and extension-contributing.',
    time: new Date().toISOString(),
  };
  ctx.output.appendLine(JSON.stringify(msg));
  return msg;
}
